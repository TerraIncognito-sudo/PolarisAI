from playwright.sync_api import sync_playwright
import tempfile; SP=tempfile.gettempdir()+"/"
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch(); pg=b.new_page(viewport={"width":1366,"height":1000})
    pg.on("pageerror",lambda e:errs.append(str(e))); pg.on("console",lambda m: errs.append(m.text) if m.type=="error" else None)
    pg.goto("http://localhost:8765/browser.html"); pg.wait_for_timeout(800)
    print("count default:", pg.inner_text("#count"), "| kpis:", pg.inner_text("#kpis").replace("\n"," "))
    print("first rows:", pg.eval_on_selector_all("#tbl tbody tr", "rs=>rs.slice(0,4).map(r=>r.innerText.replace(/\\s+/g,' '))"))
    pg.click("#f-elig + i"); pg.wait_for_timeout(200); print("all funds:", pg.inner_text("#count"))
    pg.click("#f-elig + i")
    pg.click("#cats .cat >> nth=1"); pg.click("label.tg:has(#f-cad)"); pg.select_option("#risk","low"); pg.select_option("#sort","r3:desc")
    print("US stocks, CAD, low risk, by 3yr:", pg.inner_text("#count"), pg.eval_on_selector_all("#tbl tbody tr", "rs=>rs.slice(0,3).map(r=>r.innerText.replace(/\\s+/g,' '))"))
    pg.click("#reset"); pg.fill("#q","vanguard bond"); pg.wait_for_timeout(200); print("search:", pg.inner_text("#count"))
    pg.click("#reset")
    for i in range(3): pg.click(f"#tbl tbody tr >> nth={i} >> .cbx")
    print("tray:", pg.inner_text("#tray").replace("\n"," "))
    pg.wait_for_timeout(1500)
    print("compare cols:", pg.inner_text("#cgrid").replace("\n"," ")[:400])
    print("corr:", pg.inner_text("#corrbox").replace("\n"," "))
    pg.locator("#compare").scroll_into_view_if_needed(); pg.hover("#growth", position={"x":300,"y":120}); pg.wait_for_timeout(200)
    pg.locator("#compare").screenshot(path=SP+"b_compare.png")
    pg.click("#tbl tbody tr >> nth=3 >> td.fund"); pg.wait_for_selector("#drawer"); pg.wait_for_timeout(200)
    pg.screenshot(path=SP+"b_drawer.png"); print("drawer:", pg.inner_text("#drawer")[:300].replace("\n"," | "))
    pg.keyboard.press("Escape")
    pg.evaluate("window.scrollTo(0,0)"); pg.click("#tab-c"); pg.wait_for_timeout(300)
    pg.hover("#scatter", position={"x":200,"y":200}); pg.locator(".chartcard >> nth=0").screenshot(path=SP+"b_scatter.png")
    print("scnote:", pg.inner_text("#scnote"))
    pg.click("#tab-t"); pg.evaluate("window.scrollTo(0,0)"); pg.screenshot(path=SP+"b_top.png")
    m=b.new_page(viewport={"width":390,"height":844}); m.goto("http://localhost:8765/browser.html"); m.wait_for_timeout(600)
    print("mobile scrollWidth:", m.evaluate("document.documentElement.scrollWidth")); m.screenshot(path=SP+"b_mobile.png")
    b.close()
print("ERRORS:", errs or "none")
